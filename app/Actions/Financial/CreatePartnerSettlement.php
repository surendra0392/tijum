<?php

declare(strict_types=1);

namespace App\Actions\Financial;

use App\Enums\CommissionSnapshotStatus;
use App\Enums\SettlementStatus;
use App\Models\Admin;
use App\Models\Owner;
use App\Models\PartnerSettlement;
use App\Models\PartnerSettlementItem;
use App\Models\Reservation;
use App\Services\Financial\SettlementCalculationService;
use Carbon\CarbonImmutable;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;

class CreatePartnerSettlement
{
    public function __construct(
        private readonly SettlementCalculationService $calculationService,
    ) {}

    /**
     * @param  list<int>|null  $reservationIds
     */
    public function execute(
        Owner $owner,
        Admin $admin,
        ?array $reservationIds = null,
        ?CarbonImmutable $periodStart = null,
        ?CarbonImmutable $periodEnd = null,
    ): PartnerSettlement {
        $profile = $owner->financialProfile;
        if ($profile === null || ! $profile->isSettlementEligible()) {
            throw ValidationException::withMessages([
                'settlement' => 'Partner does not have an active, verified financial profile or linked account.',
            ]);
        }

        $eligible = $this->calculationService->getEligibleReservations($owner);
        if ($reservationIds !== null) {
            $eligible = $eligible->whereIn('id', $reservationIds);
        }

        if ($eligible->isEmpty()) {
            throw ValidationException::withMessages([
                'settlement' => 'No eligible confirmed reservations found for settlement under current hold policies.',
            ]);
        }

        $now = CarbonImmutable::now();
        $start = $periodStart ?? $eligible->min('check_in_date') ?? $now;
        $end = $periodEnd ?? $eligible->max('checkout_date') ?? $now;

        $summary = $this->calculationService->calculateSettlementSummary($owner, $eligible, $now);

        return DB::transaction(function () use ($owner, $profile, $admin, $eligible, $summary, $start, $end, $now): PartnerSettlement {
            // Lock reservations under InnoDB row lock to prevent concurrent settlement generation races
            $lockedReservations = Reservation::query()
                ->whereIn('id', $eligible->pluck('id'))
                ->lockForUpdate()
                ->get();

            $alreadyProcessed = $lockedReservations->filter(function (Reservation $res): bool {
                return $res->commission_status === CommissionSnapshotStatus::SettlementPending
                    || $res->commission_status === CommissionSnapshotStatus::Settled;
            });

            if ($alreadyProcessed->isNotEmpty()) {
                throw ValidationException::withMessages([
                    'settlement' => 'One or more selected reservations are already undergoing settlement processing or have been settled.',
                ]);
            }

            $ref = 'TPS-'.$now->format('Y').'-'.strtoupper(Str::ulid()->toBase32());

            /** @var PartnerSettlement $settlement */
            $settlement = PartnerSettlement::create([
                'settlement_reference' => $ref,
                'owner_id' => $owner->id,
                'owner_financial_profile_id' => $profile->id,
                'period_start' => $start,
                'period_end' => $end,
                'currency' => 'INR',
                'gross_booking_value_minor' => $summary['gross_booking_value_minor'],
                'commission_amount_minor' => $summary['commission_amount_minor'],
                'commission_tax_amount_minor' => $summary['commission_tax_amount_minor'],
                'statutory_deductions_minor' => $summary['statutory_deductions_minor'],
                'refund_adjustments_minor' => $summary['refund_adjustments_minor'],
                'relocation_adjustments_minor' => 0,
                'other_adjustments_minor' => 0,
                'net_settlement_amount_minor' => $summary['net_settlement_amount_minor'],
                'status' => SettlementStatus::Draft,
                'admin_notes' => 'Draft settlement generated by admin '.$admin->name,
            ]);

            foreach ($summary['items'] as $item) {
                PartnerSettlementItem::create([
                    'partner_settlement_id' => $settlement->id,
                    'reservation_id' => $item['reservation_id'],
                    'reservation_payment_id' => $item['reservation_payment_id'],
                    'item_type' => $item['item_type'],
                    'gross_amount_minor' => $item['gross_amount_minor'],
                    'commission_amount_minor' => $item['commission_amount_minor'],
                    'commission_tax_amount_minor' => $item['commission_tax_amount_minor'],
                    'tax_deduction_minor' => $item['tax_deduction_minor'],
                    'refund_deduction_minor' => $item['refund_deduction_minor'],
                    'net_payable_minor' => $item['net_payable_minor'],
                    'notes' => $item['notes'],
                ]);
            }

            // Mark included reservations as settlement pending
            $eligible->each(function ($res): void {
                $res->forceFill(['commission_status' => CommissionSnapshotStatus::SettlementPending])->save();
            });

            return $settlement;
        });
    }
}
